USE AUTOMATIZACAO
GO

-- Execute este arquivo uma unica vez para atualizar o banco ja existente.
-- Ele nao apaga registros de contatos, mensagens ou envios.

ALTER TABLE automatizacao.CONTATOS_WPP
ALTER COLUMN TELEFONE NVARCHAR(20) NOT NULL
GO

IF COL_LENGTH('automatizacao.CONTROLE_ENVIO_WPP', 'STATUS') IS NULL
    ALTER TABLE automatizacao.CONTROLE_ENVIO_WPP
    ADD STATUS NVARCHAR(20) NOT NULL
        CONSTRAINT DF_CONTROLE_ENVIO_WPP_STATUS DEFAULT 'PENDENTE'
GO

IF COL_LENGTH('automatizacao.CONTROLE_ENVIO_WPP', 'TENTATIVAS') IS NULL
    ALTER TABLE automatizacao.CONTROLE_ENVIO_WPP
    ADD TENTATIVAS INT NOT NULL
        CONSTRAINT DF_CONTROLE_ENVIO_WPP_TENTATIVAS DEFAULT 0
GO

IF COL_LENGTH('automatizacao.CONTROLE_ENVIO_WPP', 'DATA_INICIO') IS NULL
    ALTER TABLE automatizacao.CONTROLE_ENVIO_WPP ADD DATA_INICIO DATETIME2 NULL
GO

IF COL_LENGTH('automatizacao.CONTROLE_ENVIO_WPP', 'DATA_ENVIO') IS NULL
    ALTER TABLE automatizacao.CONTROLE_ENVIO_WPP ADD DATA_ENVIO DATETIME2 NULL
GO

IF COL_LENGTH('automatizacao.CONTROLE_ENVIO_WPP', 'MENSAGEM_ERRO') IS NULL
    ALTER TABLE automatizacao.CONTROLE_ENVIO_WPP ADD MENSAGEM_ERRO NVARCHAR(2000) NULL
GO

IF NOT EXISTS (
    SELECT 1 FROM sys.check_constraints
    WHERE name = 'CK_CONTROLE_ENVIO_STATUS'
)
    ALTER TABLE automatizacao.CONTROLE_ENVIO_WPP
    ADD CONSTRAINT CK_CONTROLE_ENVIO_STATUS
    CHECK (STATUS IN ('PENDENTE', 'PROCESSANDO', 'ENVIADO', 'ERRO'))
GO

IF NOT EXISTS (
    SELECT 1 FROM sys.indexes
    WHERE name = 'IX_CONTROLE_ENVIO_WPP_FILA'
      AND object_id = OBJECT_ID('automatizacao.CONTROLE_ENVIO_WPP')
)
    CREATE INDEX IX_CONTROLE_ENVIO_WPP_FILA
    ON automatizacao.CONTROLE_ENVIO_WPP (STATUS, ID_CONTROLE_ENVIO)
GO

-- As chaves estrangeiras so sao criadas se os dados existentes forem validos.
IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = 'FK_CONTROLE_ENVIO_CONTATO')
AND NOT EXISTS (
    SELECT 1
    FROM automatizacao.CONTROLE_ENVIO_WPP AS envio
    LEFT JOIN automatizacao.CONTATOS_WPP AS contato ON contato.ID_CONTATO = envio.ID_CONTATO
    WHERE contato.ID_CONTATO IS NULL
)
    ALTER TABLE automatizacao.CONTROLE_ENVIO_WPP WITH CHECK
    ADD CONSTRAINT FK_CONTROLE_ENVIO_CONTATO FOREIGN KEY (ID_CONTATO)
    REFERENCES automatizacao.CONTATOS_WPP (ID_CONTATO)
GO

IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = 'FK_CONTROLE_ENVIO_TIPO')
AND NOT EXISTS (
    SELECT 1
    FROM automatizacao.CONTROLE_ENVIO_WPP AS envio
    LEFT JOIN automatizacao.TIPO_ENVIO_WPP AS tipo ON tipo.ID_TIPO_ENVIO = envio.ID_TIPO_ENVIO
    WHERE tipo.ID_TIPO_ENVIO IS NULL
)
    ALTER TABLE automatizacao.CONTROLE_ENVIO_WPP WITH CHECK
    ADD CONSTRAINT FK_CONTROLE_ENVIO_TIPO FOREIGN KEY (ID_TIPO_ENVIO)
    REFERENCES automatizacao.TIPO_ENVIO_WPP (ID_TIPO_ENVIO)
GO

IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = 'FK_CONTROLE_ENVIO_MENSAGEM')
AND NOT EXISTS (
    SELECT 1
    FROM automatizacao.CONTROLE_ENVIO_WPP AS envio
    LEFT JOIN automatizacao.MENSAGEM_WPP AS mensagem ON mensagem.ID_MENSAGEM = envio.ID_MENSAGEM
    WHERE envio.ID_MENSAGEM IS NOT NULL AND mensagem.ID_MENSAGEM IS NULL
)
    ALTER TABLE automatizacao.CONTROLE_ENVIO_WPP WITH CHECK
    ADD CONSTRAINT FK_CONTROLE_ENVIO_MENSAGEM FOREIGN KEY (ID_MENSAGEM)
    REFERENCES automatizacao.MENSAGEM_WPP (ID_MENSAGEM)
GO
