-- Migracao 000: Schema e Tabelas Iniciais (Idempotente)
-- Cria o schema automatizacao e as tabelas base caso ainda nao existam.

IF NOT EXISTS (SELECT 1 FROM sys.schemas WHERE name = 'automatizacao')
BEGIN
    EXEC('CREATE SCHEMA automatizacao');
END
GO

IF OBJECT_ID('automatizacao.TIPO_ENVIO_WPP', 'U') IS NULL
BEGIN
    CREATE TABLE automatizacao.TIPO_ENVIO_WPP (
        ID_TIPO_ENVIO BIGINT IDENTITY(1,1) PRIMARY KEY,
        DESCRICAO_TIPO_ENVIO NVARCHAR(250)
    );

    INSERT INTO automatizacao.TIPO_ENVIO_WPP (DESCRICAO_TIPO_ENVIO) VALUES ('MENSAGEM');
    INSERT INTO automatizacao.TIPO_ENVIO_WPP (DESCRICAO_TIPO_ENVIO) VALUES ('DOCUMENTO');
    INSERT INTO automatizacao.TIPO_ENVIO_WPP (DESCRICAO_TIPO_ENVIO) VALUES ('IMAGEM');
END
GO

IF OBJECT_ID('automatizacao.MENSAGEM_WPP', 'U') IS NULL
BEGIN
    CREATE TABLE automatizacao.MENSAGEM_WPP (
        ID_MENSAGEM BIGINT IDENTITY(0,1) PRIMARY KEY,
        DESCRICAO_MENSAGEM NVARCHAR(4000)
    );
END
GO

IF OBJECT_ID('automatizacao.CONTATOS_WPP', 'U') IS NULL
BEGIN
    CREATE TABLE automatizacao.CONTATOS_WPP (
        ID_CONTATO BIGINT IDENTITY(1,1) PRIMARY KEY,
        NOME NVARCHAR(250) NOT NULL,
        TELEFONE NVARCHAR(20) NOT NULL,
        ATIVO BIT NOT NULL CONSTRAINT DF_CONTATOS_WPP_ATIVO DEFAULT 1
    );
END
GO

IF OBJECT_ID('automatizacao.CONTROLE_ENVIO_WPP', 'U') IS NULL
BEGIN
    CREATE TABLE automatizacao.CONTROLE_ENVIO_WPP (
        ID_CONTROLE_ENVIO BIGINT IDENTITY(1,1) PRIMARY KEY,
        ID_CONTATO BIGINT NOT NULL,
        ID_TIPO_ENVIO BIGINT NOT NULL,
        ID_MENSAGEM BIGINT NULL,
        CAMINHO_ARQUIVO NVARCHAR(4000) NULL,
        STATUS NVARCHAR(20) NOT NULL CONSTRAINT DF_CONTROLE_ENVIO_WPP_STATUS DEFAULT 'PENDENTE',
        TENTATIVAS INT NOT NULL CONSTRAINT DF_CONTROLE_ENVIO_WPP_TENTATIVAS DEFAULT 0,
        DATA_INICIO DATETIME2 NULL,
        DATA_ENVIO DATETIME2 NULL,
        MENSAGEM_ERRO NVARCHAR(2000) NULL,
        CONSTRAINT FK_CONTROLE_ENVIO_CONTATO FOREIGN KEY (ID_CONTATO)
            REFERENCES automatizacao.CONTATOS_WPP (ID_CONTATO),
        CONSTRAINT FK_CONTROLE_ENVIO_TIPO FOREIGN KEY (ID_TIPO_ENVIO)
            REFERENCES automatizacao.TIPO_ENVIO_WPP (ID_TIPO_ENVIO),
        CONSTRAINT FK_CONTROLE_ENVIO_MENSAGEM FOREIGN KEY (ID_MENSAGEM)
            REFERENCES automatizacao.MENSAGEM_WPP (ID_MENSAGEM),
        CONSTRAINT CK_CONTROLE_ENVIO_STATUS CHECK (STATUS IN ('PENDENTE', 'PROCESSANDO', 'ENVIADO', 'ERRO'))
    );

    CREATE INDEX IX_CONTROLE_ENVIO_WPP_FILA
        ON automatizacao.CONTROLE_ENVIO_WPP (STATUS, ID_CONTROLE_ENVIO);
END
GO
