USE AUTOMATIZACAO;
GO

-- Migracao 001: Evolucao de Schema para Catalogo de Mensagens, Filas Persistentes e Rastreabilidade
-- Esta migracao e estritamente nao-destrutiva e idempotente.
-- Preserva todas as tabelas e dados existentes sem TRUNCATE ou DROP.

-- 1. Garante tipos de envio padrao em automatizacao.TIPO_ENVIO_WPP
IF NOT EXISTS (SELECT 1 FROM automatizacao.TIPO_ENVIO_WPP WHERE DESCRICAO_TIPO_ENVIO = 'MENSAGEM')
    INSERT INTO automatizacao.TIPO_ENVIO_WPP (DESCRICAO_TIPO_ENVIO) VALUES ('MENSAGEM');

IF NOT EXISTS (SELECT 1 FROM automatizacao.TIPO_ENVIO_WPP WHERE DESCRICAO_TIPO_ENVIO = 'DOCUMENTO')
    INSERT INTO automatizacao.TIPO_ENVIO_WPP (DESCRICAO_TIPO_ENVIO) VALUES ('DOCUMENTO');

IF NOT EXISTS (SELECT 1 FROM automatizacao.TIPO_ENVIO_WPP WHERE DESCRICAO_TIPO_ENVIO = 'IMAGEM')
    INSERT INTO automatizacao.TIPO_ENVIO_WPP (DESCRICAO_TIPO_ENVIO) VALUES ('IMAGEM');
GO

-- 2. Evolucao de automatizacao.MENSAGEM_WPP
-- Adiciona CODIGO_MENSAGEM, ARQUIVO, ATIVO, DATA_CRIACAO, DATA_ATUALIZACAO
IF COL_LENGTH('automatizacao.MENSAGEM_WPP', 'CODIGO_MENSAGEM') IS NULL
    ALTER TABLE automatizacao.MENSAGEM_WPP
    ADD CODIGO_MENSAGEM NVARCHAR(100) NULL;
GO

IF COL_LENGTH('automatizacao.MENSAGEM_WPP', 'ARQUIVO') IS NULL
    ALTER TABLE automatizacao.MENSAGEM_WPP
    ADD ARQUIVO NVARCHAR(500) NULL;
GO

IF COL_LENGTH('automatizacao.MENSAGEM_WPP', 'ATIVO') IS NULL
    ALTER TABLE automatizacao.MENSAGEM_WPP
    ADD ATIVO BIT NOT NULL CONSTRAINT DF_MENSAGEM_WPP_ATIVO DEFAULT 1;
GO

IF COL_LENGTH('automatizacao.MENSAGEM_WPP', 'DATA_CRIACAO') IS NULL
    ALTER TABLE automatizacao.MENSAGEM_WPP
    ADD DATA_CRIACAO DATETIME2 NOT NULL CONSTRAINT DF_MENSAGEM_WPP_DATA_CRIACAO DEFAULT SYSDATETIME();
GO

IF COL_LENGTH('automatizacao.MENSAGEM_WPP', 'DATA_ATUALIZACAO') IS NULL
    ALTER TABLE automatizacao.MENSAGEM_WPP
    ADD DATA_ATUALIZACAO DATETIME2 NOT NULL CONSTRAINT DF_MENSAGEM_WPP_DATA_ATUALIZACAO DEFAULT SYSDATETIME();
GO

IF NOT EXISTS (
    SELECT 1 FROM sys.indexes
    WHERE name = 'UQ_MENSAGEM_WPP_CODIGO'
      AND object_id = OBJECT_ID('automatizacao.MENSAGEM_WPP')
)
    CREATE UNIQUE INDEX UQ_MENSAGEM_WPP_CODIGO
    ON automatizacao.MENSAGEM_WPP (CODIGO_MENSAGEM)
    WHERE CODIGO_MENSAGEM IS NOT NULL;
GO

-- 3. Evolucao de automatizacao.CONTATOS_WPP (Normalizacao e LGPD)
IF COL_LENGTH('automatizacao.CONTATOS_WPP', 'TELEFONE_NORMALIZADO') IS NULL
    ALTER TABLE automatizacao.CONTATOS_WPP
    ADD TELEFONE_NORMALIZADO NVARCHAR(20) NULL;
GO

IF COL_LENGTH('automatizacao.CONTATOS_WPP', 'CONSENTIMENTO_STATUS') IS NULL
    ALTER TABLE automatizacao.CONTATOS_WPP
    ADD CONSENTIMENTO_STATUS NVARCHAR(50) NOT NULL CONSTRAINT DF_CONTATOS_WPP_CONSENTIMENTO_STATUS DEFAULT 'OPT_IN';
GO

IF COL_LENGTH('automatizacao.CONTATOS_WPP', 'CONSENTIMENTO_DATA') IS NULL
    ALTER TABLE automatizacao.CONTATOS_WPP
    ADD CONSENTIMENTO_DATA DATETIME2 NULL;
GO

IF COL_LENGTH('automatizacao.CONTATOS_WPP', 'CONSENTIMENTO_ORIGEM') IS NULL
    ALTER TABLE automatizacao.CONTATOS_WPP
    ADD CONSENTIMENTO_ORIGEM NVARCHAR(250) NULL;
GO

IF COL_LENGTH('automatizacao.CONTATOS_WPP', 'BLOQUEADO') IS NULL
    ALTER TABLE automatizacao.CONTATOS_WPP
    ADD BLOQUEADO BIT NOT NULL CONSTRAINT DF_CONTATOS_WPP_BLOQUEADO DEFAULT 0;
GO

IF COL_LENGTH('automatizacao.CONTATOS_WPP', 'DATA_ATUALIZACAO') IS NULL
    ALTER TABLE automatizacao.CONTATOS_WPP
    ADD DATA_ATUALIZACAO DATETIME2 NOT NULL CONSTRAINT DF_CONTATOS_WPP_DATA_ATUALIZACAO DEFAULT SYSDATETIME();
GO

IF NOT EXISTS (
    SELECT 1 FROM sys.indexes
    WHERE name = 'UQ_CONTATOS_WPP_TELEFONE_NORMALIZADO'
      AND object_id = OBJECT_ID('automatizacao.CONTATOS_WPP')
)
    CREATE UNIQUE INDEX UQ_CONTATOS_WPP_TELEFONE_NORMALIZADO
    ON automatizacao.CONTATOS_WPP (TELEFONE_NORMALIZADO)
    WHERE TELEFONE_NORMALIZADO IS NOT NULL;
GO

-- 4. Tabela de Solicitacoes de Envio (Originadas do Google Sheets com ID_CONTROLE)
IF OBJECT_ID('automatizacao.SOLICITACOES_ENVIO_WPP', 'U') IS NULL
BEGIN
    CREATE TABLE automatizacao.SOLICITACOES_ENVIO_WPP (
        ID_SOLICITACAO BIGINT IDENTITY(1,1) PRIMARY KEY,
        ID_CONTROLE_SHEETS NVARCHAR(100) NOT NULL,
        ID_CONTATO BIGINT NOT NULL,
        STATUS_OPERADOR NVARCHAR(50) NOT NULL CONSTRAINT DF_SOLICITACOES_STATUS_OPERADOR DEFAULT 'Pendente',
        STATUS_TECNICO NVARCHAR(50) NOT NULL CONSTRAINT DF_SOLICITACOES_STATUS_TECNICO DEFAULT 'PENDENTE',
        CODIGOS_MENSAGENS NVARCHAR(500) NULL,
        DATA_SOLICITACAO_SHEETS DATETIME2 NULL,
        DATA_CRIACAO DATETIME2 NOT NULL CONSTRAINT DF_SOLICITACOES_DATA_CRIACAO DEFAULT SYSDATETIME(),
        DATA_INICIO DATETIME2 NULL,
        DATA_CONCLUSAO DATETIME2 NULL,
        MENSAGEM_ERRO NVARCHAR(2000) NULL,
        CONSTRAINT FK_SOLICITACOES_CONTATO FOREIGN KEY (ID_CONTATO)
            REFERENCES automatizacao.CONTATOS_WPP (ID_CONTATO),
        CONSTRAINT CK_SOLICITACOES_STATUS_TECNICO CHECK (
            STATUS_TECNICO IN ('PENDENTE', 'PROCESSANDO', 'CONCLUIDO', 'FALHA_PARCIAL', 'ERRO', 'CANCELADO', 'NAO_ELEGIVEL')
        )
    );

    CREATE UNIQUE INDEX UQ_SOLICITACOES_ID_SHEETS
        ON automatizacao.SOLICITACOES_ENVIO_WPP (ID_CONTROLE_SHEETS);

    CREATE INDEX IX_SOLICITACOES_STATUS
        ON automatizacao.SOLICITACOES_ENVIO_WPP (STATUS_TECNICO, STATUS_OPERADOR);
END;
GO

-- 5. Tabela de Etapas Individuais de Envio por Solicitacao (Preserva a ordem 1, 2, 3...)
IF OBJECT_ID('automatizacao.ETAPAS_SOLICITACAO_WPP', 'U') IS NULL
BEGIN
    CREATE TABLE automatizacao.ETAPAS_SOLICITACAO_WPP (
        ID_ETAPA BIGINT IDENTITY(1,1) PRIMARY KEY,
        ID_SOLICITACAO BIGINT NOT NULL,
        ORDEM INT NOT NULL,
        CODIGO_MENSAGEM NVARCHAR(100) NOT NULL,
        ID_MENSAGEM BIGINT NULL,
        ID_TIPO_ENVIO BIGINT NOT NULL,
        CAMINHO_ARQUIVO NVARCHAR(4000) NULL,
        TEXTO_RENDERIZADO NVARCHAR(MAX) NULL,
        STATUS NVARCHAR(50) NOT NULL CONSTRAINT DF_ETAPAS_STATUS DEFAULT 'PENDENTE',
        TENTATIVAS INT NOT NULL CONSTRAINT DF_ETAPAS_TENTATIVAS DEFAULT 0,
        DATA_INICIO DATETIME2 NULL,
        DATA_ENVIO DATETIME2 NULL,
        MENSAGEM_ERRO NVARCHAR(2000) NULL,
        CHAVE_IDEMPOTENCIA NVARCHAR(250) NOT NULL,
        CONSTRAINT FK_ETAPAS_SOLICITACAO FOREIGN KEY (ID_SOLICITACAO)
            REFERENCES automatizacao.SOLICITACOES_ENVIO_WPP (ID_SOLICITACAO),
        CONSTRAINT FK_ETAPAS_MENSAGEM FOREIGN KEY (ID_MENSAGEM)
            REFERENCES automatizacao.MENSAGEM_WPP (ID_MENSAGEM),
        CONSTRAINT FK_ETAPAS_TIPO_ENVIO FOREIGN KEY (ID_TIPO_ENVIO)
            REFERENCES automatizacao.TIPO_ENVIO_WPP (ID_TIPO_ENVIO),
        CONSTRAINT CK_ETAPAS_STATUS CHECK (
            STATUS IN ('PENDENTE', 'PROCESSANDO', 'ENVIADO', 'ERRO', 'CANCELADO', 'PULADO')
        )
    );

    CREATE UNIQUE INDEX UQ_ETAPAS_IDEMPOTENCIA
        ON automatizacao.ETAPAS_SOLICITACAO_WPP (CHAVE_IDEMPOTENCIA);

    CREATE INDEX IX_ETAPAS_FILA
        ON automatizacao.ETAPAS_SOLICITACAO_WPP (STATUS, ID_SOLICITACAO, ORDEM);
END;
GO

-- 6. Tabela de Historico de Tentativas e Auditoria (Rastreabilidade e LGPD)
IF OBJECT_ID('automatizacao.HISTORICO_TENTATIVAS_ENVIO_WPP', 'U') IS NULL
BEGIN
    CREATE TABLE automatizacao.HISTORICO_TENTATIVAS_ENVIO_WPP (
        ID_TENTATIVA BIGINT IDENTITY(1,1) PRIMARY KEY,
        ID_ETAPA BIGINT NOT NULL,
        NUMERO_TENTATIVA INT NOT NULL,
        CANAL NVARCHAR(50) NOT NULL,
        RESULTADO NVARCHAR(50) NOT NULL,
        DETALHE NVARCHAR(MAX) NULL,
        DATA_TENTATIVA DATETIME2 NOT NULL CONSTRAINT DF_HISTORICO_DATA DEFAULT SYSDATETIME(),
        CONSTRAINT FK_HISTORICO_ETAPA FOREIGN KEY (ID_ETAPA)
            REFERENCES automatizacao.ETAPAS_SOLICITACAO_WPP (ID_ETAPA),
        CONSTRAINT CK_HISTORICO_RESULTADO CHECK (
            RESULTADO IN ('SUCESSO', 'FALHA', 'INCERTO')
        )
    );

    CREATE INDEX IX_HISTORICO_ETAPA
        ON automatizacao.HISTORICO_TENTATIVAS_ENVIO_WPP (ID_ETAPA, DATA_TENTATIVA);
END;
GO
